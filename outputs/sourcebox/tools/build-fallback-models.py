"""Author original block figures, compile once for distribution (no game mesh input)."""
import json, pathlib, subprocess, sys, shutil, struct
root=pathlib.Path(sys.argv[1]).resolve(); compiler=pathlib.Path(sys.argv[2]).resolve()
root.mkdir(parents=True,exist_ok=True)
(root/'gameinfo.txt').write_text('"GameInfo" { game "SourceBox fallback build" FileSystem { SteamAppId 243750 SearchPaths { Game "|gameinfo_path|." } } }')
nodes=['0 "root" -1','1 "weapon_bone" 0','2 "bip01_r_hand" 0','3 "wrist_R" 0']
pose=['0 0 0 0 0 0 0','1 8 -12 45 0 0 0','2 8 -12 45 0 0 0','3 8 -12 45 0 0 0']
header=['version 1','nodes',*nodes,'end','skeleton','time 0',*pose,'end']
mesh=header+['triangles']
def box(lo,hi):
 v=[(x,y,z) for x in (lo[0],hi[0]) for y in (lo[1],hi[1]) for z in (lo[2],hi[2])]
 for a,b,c,d in [(0,1,3,2),(4,6,7,5),(0,4,5,1),(2,3,7,6),(0,2,6,4),(1,5,7,3)]:
  for tri in [(a,b,c),(a,c,d)]:
   mesh.append('fallback')
   for i in tri:mesh.append('0 '+' '.join(map(str,v[i]))+' 0 0 1 0 0')
for lo,hi in [((-7,-10,28),(7,10,54)),((-6,-6,55),(6,6,68)),((-5,-10,0),(5,-2,28)),((-5,2,0),(5,10,28)),((-5,-16,30),(5,-11,52)),((-5,11,30),(5,16,52))]:box(lo,hi)
mesh+=['end'];(root/'mesh.smd').write_text('\n'.join(mesh)+'\n');(root/'idle.smd').write_text('\n'.join(header)+'\n')
(root/'model.qc').write_text('$modelname "sourcebox/fallback/person.mdl"\n$body body "mesh.smd"\n$cdmaterials "sourcebox/fallback"\n$sequence idle "idle.smd" fps 30 loop\n$sequence run "idle.smd" fps 30 loop\n$sequence air "idle.smd" fps 30 loop\n$bbox -16 -16 0 16 16 72\n$bonemerge weapon_bone\n$bonemerge bip01_r_hand\n$bonemerge wrist_R\n$attachment "anim_attachment_RH" "weapon_bone" 0 0 0\n')
subprocess.run([str(compiler),'-game',str(root),str(root/'model.qc')],check=True,stdout=subprocess.PIPE,stderr=subprocess.STDOUT)
mat=root/'materials/sourcebox/fallback/fallback.vmt';mat.parent.mkdir(parents=True,exist_ok=True)
mat.write_text('"VertexLitGeneric" { "$basetexture" "sourcebox/fallback/cyan" "$halflambert" "1" }')
header=bytearray(80);header[:4]=b'VTF\0';struct.pack_into('<IIIHHIHH',header,4,7,2,80,4,4,0,1,0)
struct.pack_into('<fI',header,48,1.0,0);header[56]=1;struct.pack_into('<I',header,57,0xffffffff);struct.pack_into('<H',header,63,1)
(mat.parent/'cyan.vtf').write_bytes(header+bytes([26,204,230,255])*16)
# A separate original block tool, never the person mesh, for missing gun assets.
mesh=['version 1','nodes',*nodes,'end','skeleton','time 0',*pose,'end','triangles']
for lo,hi in [((-6,-4,-4),(15,4,4)),((-4,-3,-12),(1,3,-4)),((15,-2,-2),(23,2,2))]:box(lo,hi)
mesh+=['end'];(root/'gun.smd').write_text('\n'.join(mesh)+'\n')
(root/'gun.qc').write_text('$modelname "sourcebox/fallback/tool.mdl"\n$body body "gun.smd"\n$cdmaterials "sourcebox/fallback"\n$sequence idle "idle.smd" fps 30 loop\n$sequence draw "idle.smd" fps 30\n$sequence fire "idle.smd" fps 30\n')
subprocess.run([str(compiler),'-game',str(root),str(root/'gun.qc')],check=True,stdout=subprocess.PIPE,stderr=subprocess.STDOUT)
aliases={}
for name in ['heavy','soldier','gmod']:aliases['models/sourcebox/portal2/peers/'+name+'.mdl']='always'
aliases['models/sourcebox/portal2/chell.mdl']='always'
aliases['models/sourcebox/hl2/player.mdl']='always'
for name in ['scout','sniper','soldier','demo','demoman','medic','heavy','pyro','spy','engineer']:aliases['models/player/'+name+'.mdl']='tf2'
aliases['models/player/kleiner.mdl']='gmod'
for name in ['gordon','zombie','scientist','robo','hgrunt','helmet','gman','gina','barney']:aliases[f'models/player/mp/{name}/{name}.mdl']='hl1mp'
aliases['models/sourcebox/portal2/v_portalgun.mdl']='always'
aliases['models/sourcebox/portal2/w_portalgun.mdl']='always'
for model in aliases:
 base=root/('models/sourcebox/fallback/tool' if model.endswith(('v_portalgun.mdl','w_portalgun.mdl')) else 'models/sourcebox/fallback/person')
 for suffix in ['.mdl','.vvd','.dx90.vtx','.dx80.vtx','.sw.vtx']:
  source=pathlib.Path(str(base)+suffix)
  if not source.exists():continue
  target=root/(model[:-4]+suffix);target.parent.mkdir(parents=True,exist_ok=True)
  data=bytearray(source.read_bytes())
  if suffix=='.mdl':
   name=model[7:].encode();assert len(name)<64;data[12:76]=name+b'\0'*(64-len(name))
  target.write_bytes(data)
(root/'aliases.json').write_text(json.dumps(aliases,indent=2))
(root/'PROVENANCE.txt').write_text('Original SourceBox block-person geometry generated by build-fallback-models.py. No extracted game content. Static debug placeholder, not a character integration.')
print('Compiled',len(aliases),'original fallback aliases')
